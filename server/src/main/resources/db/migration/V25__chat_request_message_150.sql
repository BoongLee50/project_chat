-- 대화 신청 한마디를 **150자**로 되돌린다(기획 확인 2026-09-19).
--
-- V19가 100 → 200으로 넓힌 근거는 **시안 img09의 입력칸 `0/200`** 이었다. 그런데 기획서
-- **본문 4-3은 그때도 지금도 "최대 150자"** 다 — 한 번도 바뀐 적이 없어서 판 사이 diff로는
-- 드러나지 않았고, 본문을 처음부터 훑고서야 나왔다(07 §3 함정 #71).
-- 기획 확인 결과 **본문이 맞다**. 시안의 `0/200`이 낡은 표기다.
--
-- ▸ 🚨 이번엔 **좁히는 방향**이다 — V19가 *"반대로 좁힐 때만 조심하면 된다"* 고 적어 둔 그 경우다.
--   MariaDB는 strict 모드에서 넘치는 행이 하나라도 있으면 `Data too long`(1406)으로 ALTER를
--   거부한다. 서버가 아예 안 뜨므로, 넘치는 행을 **먼저 잘라 두고** 폭을 줄인다.
--
-- ▸ 자르는 것이 왜 괜찮은가
--   150자를 넘는 행은 **잘못된 한도(200)로 받아 놓은 것**이고, 아직 출시 전이라 개발 데이터뿐이다.
--   신청 한마디는 첫인사라 뒤 50자가 잘려도 맥락이 남는다. 그래도 **조용히 지우는 것은 아니다** —
--   이 주석이 그 기록이고, 실행 전 개수는 아래 질의로 미리 볼 수 있다:
--     SELECT COUNT(*) FROM chat_requests WHERE CHAR_LENGTH(message) > 150;
--
-- ▸ 길이 검사는 여전히 서버가 한다
--   컬럼 폭은 마지막 방어선이지 규칙이 아니다. 규칙은 `app.chat.request-message-max-length`이고,
--   초과하면 `field`에 한도를 실어 돌려보내 화면이 문구를 만든다. 설정을 바꿀 때
--   **이 컬럼 폭도 같이 봐야 한다** — 설정만 늘리면 DB가 먼저 거부한다.

UPDATE chat_requests
SET message = LEFT(message, 150)
WHERE CHAR_LENGTH(message) > 150;

ALTER TABLE chat_requests
    MODIFY COLUMN message VARCHAR(150) NOT NULL COMMENT '대화 신청 한마디(150자, 기획 4-3 본문)';
