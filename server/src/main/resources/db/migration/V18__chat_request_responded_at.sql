-- 거절당한 상대에게 **1일간 대화 신청 불가**(기획 §2-5).
--
-- ▸ 왜 컬럼이 하나 더 필요한가
--   `chat_requests`에는 `created_at`(보낸 시각)만 있다. "거절당한 지 하루"를 재려면
--   **거절한 시각**이 있어야 한다. created_at으로 재면 사흘 전에 보낸 신청을 오늘 거절해도
--   이미 하루가 지난 것이 되어 곧바로 다시 보낼 수 있다.
--
-- ▸ 왜 차단 표를 따로 만들지 않았나
--   막는 근거가 곧 그 거절 자체다. 별도 표를 만들면 거절과 차단이 어긋날 수 있고
--   (거절은 지웠는데 차단만 남는 식), 만료를 지우는 배치도 하나 더 는다.
--   상태가 REJECTED이고 responded_at이 24시간 안이면 막는다 — 그게 전부다.
--
-- ▸ 수락에도 같이 찍는다
--   "언제 답했는가"는 거절만의 사실이 아니다. 수락 시각도 나중에 쓸 데가 있고,
--   거절에만 찍으면 컬럼 이름과 실제가 어긋난다.
--
--   기존 행은 NULL이다 — 답한 적 없는 것이 아니라 **그때는 시각을 남기지 않았다**는 뜻이다.
--   NULL이면 막지 않는다(과거 거절로 지금 사람을 막는 것은 옳지 않다).

ALTER TABLE chat_requests
    ADD COLUMN responded_at DATETIME NULL COMMENT '수락/거절한 시각. 거절 후 1일 차단 계산의 기준';
