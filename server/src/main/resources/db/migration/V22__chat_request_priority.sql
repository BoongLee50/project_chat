-- 프라임의 **대화 신청 우선 노출**(기획 9-1 화면 26).
--
-- 기획서: *"[대화 신청] 사용 시 상대방의 받은 신청 목록에 **1일간 최상단**에 배치한다.
--          그 이후는 무료 사용자와 동일한 순서로 처리. 다른 프라임 멤버십 가입자가
--          동일인에게 대화 신청할 경우 **신청 시간에 따라** 차순위로 밀려난다."*
--
-- ▸ 왜 "지금 프라임인가"를 보면 안 되나
--   목록을 그릴 때 신청자의 구독을 조회하면, **구독이 끝난 순간 옛 신청들이 한꺼번에
--   아래로 떨어진다.** 우선권은 신청한 그 시점에 산 것이다 — 그때 정해서 못 박아 둔다.
--
-- ▸ 왜 boolean이 아니라 시각인가
--   "1일간"이 규칙의 일부다. boolean이면 만료를 계산할 근거가 사라져
--   `created_at + 1일`을 목록 질의가 매번 다시 알아야 한다. 값 하나로 끝낸다.
--
--   NULL = 우선권 없음(무료 사용자, 그리고 이 컬럼 이전의 모든 신청).

ALTER TABLE chat_requests
    ADD COLUMN priority_until DATETIME NULL
        COMMENT '이 시각까지 받은 신청 목록 최상단(프라임). NULL이면 우선권 없음';

-- 목록은 (우선권 살아 있는가, 신청 시각) 두 축으로 정렬한다.
CREATE INDEX idx_chat_requests_priority
    ON chat_requests (to_user, status, priority_until);
