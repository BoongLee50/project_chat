-- 마지막 접속 시각 — 친구 목록의 `● 1시간 전 접속` 표시(기획 7-1).
--
-- ▸ 왜 프레즌스로는 안 되나
--   프레즌스(`presence:{userId}`)는 **60초 TTL**이다. 지금 접속 중인지만 알 뿐,
--   60초가 지나면 키가 사라져 "언제 마지막으로 있었는지"는 남지 않는다.
--   시안은 오프라인인 사람에게도 `1시간 전 접속` / `2시간 전 접속`을 보여 준다.
--
-- ▸ 왜 users에 두나
--   접속은 사람에게 붙는 사실이지 세션·방에 붙는 게 아니다. 목록 질의가 이미
--   users를 조인하므로 표를 더 만들면 조인만 늘어난다.
--
-- ▸ 쓰기 부담
--   하트비트는 사람마다 30~60초에 한 번씩 온다. 그대로 UPDATE하면 접속자 수만큼
--   초당 쓰기가 생기므로 **앱에서 N분에 한 번으로 눌러서** 쓴다(LastSeenService).
--   그래서 이 값은 분 단위로 뒤처질 수 있는데, "1시간 전 접속"을 그리는 데는 충분하다.
--
--   NULL은 "한 번도 접속한 적 없음"이다 — 0으로 채우지 않는다(삭제와 빈자리는 다르다).

ALTER TABLE users
    ADD COLUMN last_seen_at DATETIME NULL COMMENT '마지막 접속(하트비트) 시각, 분 단위로 뒤처질 수 있음';
