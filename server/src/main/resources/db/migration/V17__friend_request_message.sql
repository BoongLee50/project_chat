-- 친구 신청 한마디 — **25자**(기획 5-1 · 7-1).
--
-- 시안의 받은 신청 목록은 이름 아래에 신청자가 남긴 말을 보여 준다.
-- 지금까지는 친구 요청에 말이 없어서, 화면에는 "친구 요청을 보냈어요" 같은
-- **우리가 지어낸 문구**가 들어가 있었다. 그건 상대가 한 말이 아니다.
--
-- ▸ 왜 25자인가
--   기획서가 정한 값이다. 대화 신청(100자)보다 훨씬 짧은 건 친구 신청이
--   대화를 여는 자리가 아니라 인사 한 줄이기 때문이다.
--   **길이는 서버가 잰다** — 화면에서만 막으면 API로 뚫린다.
--
-- ▸ NULL을 허용하는 이유
--   이 컬럼이 생기기 전에 오간 요청에는 말이 없다. 빈 문자열로 채우면
--   "아무 말도 안 하고 보냈다"와 "그때는 말할 자리가 없었다"가 섞인다.
--   (삭제와 빈자리는 다르다)

ALTER TABLE friendships
    ADD COLUMN message VARCHAR(25) NULL COMMENT '친구 신청 한마디(25자). 이 컬럼 이전 요청은 NULL';
