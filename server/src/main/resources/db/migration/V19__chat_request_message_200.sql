-- 대화 신청 한마디를 **200자**로 넓힌다(기획 4-3 img09의 `0/200`).
--
-- 지금까지 100자였던 건 Plan_2 기준이다. Plan_3 시안의 입력칸이 `0/200`으로 바뀌었고,
-- 친구 신청(25자)과 달리 대화 신청은 **첫인사를 제대로 쓰는 자리**라 길이가 다르다.
--
-- ▸ 넓히는 방향이라 기존 행은 그대로 산다
--   VARCHAR을 늘리는 것은 값을 자르지 않는다. 반대로 좁힐 때만 조심하면 된다.
--
-- ▸ 길이 검사는 서버가 한다
--   컬럼 폭은 마지막 방어선이지 규칙이 아니다. 규칙은 `app.chat.request-message-max-length`이고,
--   초과하면 `field`에 한도를 실어 돌려보내 화면이 문구를 만든다(②단계에서 세운 방식).

ALTER TABLE chat_requests
    MODIFY COLUMN message VARCHAR(200) NOT NULL COMMENT '대화 신청 한마디(200자, 기획 4-3)';
