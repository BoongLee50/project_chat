-- 친구 관리 개편(기획서 260919 7-1·7-2).
--
-- ① **목록 상단 고정** — "[친구 관리] 팝업창에서 [목록 상단 고정] 메뉴 선택 시 최신순으로
--    친구목록 상단에 고정 (핀마크 표시 포함)".
--
--    🚨 고정은 **보는 사람마다 따로**다. `friendships`는 두 사람이 한 행을 같이 쓰므로
--    칼럼 하나로는 "A는 B를 고정했지만 B는 A를 고정하지 않았다"를 담을 수 없다 —
--    신청한 쪽·받은 쪽 칼럼을 따로 둔다.
--
--    📌 별도 표(friend_pins)로 빼지 않은 이유: 친구 해제·차단은 **이 행을 지우는 것**이라
--    칼럼으로 두면 고정도 저절로 함께 사라진다. 따로 두면 지울 때마다 치워 줘야 하고,
--    한 번 빠뜨리면 다시 친구가 됐을 때 옛 고정이 되살아난다.
--
--    "최신순" = 고정한 시각이 늦은 것이 위다. 그래서 불린이 아니라 **시각**을 담는다.
--
-- ② **받은 친구 신청을 열어 봤는가** — 7-2 "[받은 신청]의 화면 구성과 기능은 [대화 목록]창과 동일".
--    대화방 받은 신청의 `N`(V26 `chat_requests.viewed_at`)과 같은 뜻이다.
--    받는 사람이 그 신청의 상세(= [포스트 정보])를 열 때 채운다. NULL이면 안 열어 봤다.
--
-- ⚠️ "신규 등록(수락 후 7일, N마크)"은 칼럼이 필요 없다 — `accepted_at`으로 계산된다.

ALTER TABLE friendships
    ADD COLUMN requester_pinned_at DATETIME NULL COMMENT '신청한 쪽이 상대를 목록 상단에 고정한 시각(V27)',
    ADD COLUMN addressee_pinned_at DATETIME NULL COMMENT '받은 쪽이 상대를 목록 상단에 고정한 시각(V27)',
    ADD COLUMN viewed_at           DATETIME NULL COMMENT '받는 사람이 신청을 처음 열어 본 시각(V27). NULL이면 미확인';
