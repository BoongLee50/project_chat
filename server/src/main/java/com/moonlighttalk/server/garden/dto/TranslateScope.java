package com.moonlighttalk.server.garden.dto;

/// 번역이 일어나는 자리. 무료 쿼터가 자리마다 다르다. (01 §1.4)
public enum TranslateScope {
    /// 달빛가든 댓글 — 댓글창 **5회 호출**까지 무료(영업일마다).
    COMMENT,

    /// 채팅 — 무료로 켤 수 있는 **대화방 5개**(평생).
    CHAT,

    /// 프로필 보기 — 항상 무료(쿼터를 세지 않는다).
    PROFILE,

    /// 받은 대화 신청의 한마디 — **항상 무료**(기획사항 2026-09-19: "여기서 번역은 무조건 공짜").
    ///
    /// PROFILE과 같이 처리되지만 자리를 따로 둔다 — 두 자리의 규칙이 갈라질 때
    /// 호출부를 찾아다니지 않아도 되게 하려는 것이다.
    REQUEST
}
